#!/usr/bin/env python3
r"""Write sw.js + version.js.
v3: only the app shell (html/css/js/data/fonts/icons/manifest) is precached under a content-hash VERSION.
Voice clips (audio/**/*.mp3) are cached at runtime, as they are played or warmed, in a separate
long-lived cache (AUDIO_CACHE) that survives app updates. Bump AUDIO_CACHE only if existing clips
are regenerated under the same file names."""
import os, hashlib, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO_CACHE = 'wes-audio-1'
core = ['./', 'index.html', 'style.css', 'app.js', 'data.js', 'content.js', 'audio/manifest.js', 'manifest.webmanifest', 'version.js']
for d in ['fonts', 'icons']:
    for dp, _, fs in os.walk(os.path.join(ROOT, d)):
        for f in sorted(fs):
            if not f.startswith('.'): core.append(os.path.relpath(os.path.join(dp, f), ROOT))
h = hashlib.sha1()
for f in core:
    p = os.path.join(ROOT, f)
    if os.path.isfile(p) and f != 'version.js': h.update(open(p, 'rb').read())
# include the audio file list so new clips also produce a new build number
for dp, _, fs in sorted(os.walk(os.path.join(ROOT, 'audio'))):
    for f in sorted(fs): h.update(f.encode())
ver = h.hexdigest()[:10]
sw = """/* generated by tools/build_sw.py */
const VERSION = 'wes-reading-%(ver)s';
const AUDIO_CACHE = '%(ac)s';
const CORE = %(core)s;
self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(VERSION);
    await Promise.all(CORE.map(f => fetch(new Request(f, { cache: 'reload' })).then(r => { if (!r.ok) throw new Error(f); return c.put(f, r); })));
    self.skipWaiting();
  })());
});
self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    const ac = await caches.open(AUDIO_CACHE);
    for (const k of await caches.keys()) {
      if (k === VERSION || k === AUDIO_CACHE) continue;
      // carry voice clips over from older app caches (v1/v2 precached them) so offline keeps working
      if (k.startsWith('wes-reading-')) {
        try { const old = await caches.open(k); for (const req of await old.keys()) if (/\\/audio\\/.+\\.mp3$/.test(new URL(req.url).pathname) && !(await ac.match(req))) { const r = await old.match(req); if (r) await ac.put(req, r); } } catch (err) {}
      }
      await caches.delete(k);
    }
    await self.clients.claim();
  })());
});
function ranged(hit, range) {
  return hit.arrayBuffer().then(buf => {
    const len = buf.byteLength, m = /bytes=(\\d*)-(\\d*)/.exec(range) || [];
    let s = m[1] ? parseInt(m[1], 10) : 0, en = m[2] ? parseInt(m[2], 10) : len - 1;
    if (!m[1] && m[2]) { s = Math.max(0, len - parseInt(m[2], 10)); en = len - 1; }
    en = Math.min(en, len - 1);
    if (s >= len || s > en) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + len } });
    // Safari's media player asks for byte ranges; answering with a full 200 makes playback fail/stall.
    return new Response(buf.slice(s, en + 1), { status: 206, statusText: 'Partial Content', headers: {
      'Content-Type': hit.headers.get('Content-Type') || 'audio/mpeg', 'Content-Range': 'bytes ' + s + '-' + en + '/' + len,
      'Content-Length': String(en - s + 1), 'Accept-Ranges': 'bytes' } });
  });
}
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  const isAudio = /\\/audio\\/.+\\.mp3$/.test(url.pathname);
  e.respondWith((async () => {
    const c = await caches.open(isAudio ? AUDIO_CACHE : VERSION);
    const range = e.request.headers.get('range');
    const key = url.origin + url.pathname;
    let hit = await c.match(key, { ignoreSearch: true, ignoreVary: true });
    if (!hit && !isAudio) hit = await c.match(e.request, { ignoreSearch: true });
    if (hit && range) return ranged(hit, range);
    if (hit) return hit;
    try {
      // fetch the whole file (no Range) so it can be cached, then answer the range from it
      const r = await fetch(range ? new Request(key) : e.request);
      if (r.ok && r.status === 200) { await c.put(key, r.clone()); if (range) return ranged(r, range); }
      return r;
    } catch (err) {
      if (e.request.mode === 'navigate') return (await c.match('index.html')) || Response.error();
      return Response.error();
    }
  })());
});
""" % dict(ver=ver, ac=AUDIO_CACHE, core=json.dumps(core))
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
open(os.path.join(ROOT, 'version.js'), 'w').write("window.APP_BUILD='%s';\n" % ver)
print('sw.js', ver, len(core), 'core files; audio cached at runtime in', AUDIO_CACHE)

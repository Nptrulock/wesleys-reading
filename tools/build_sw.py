#!/usr/bin/env python3
"""Write sw.js with a precache list of every app file + audio clip and a content-hash version."""
import os, hashlib, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = ['./', 'index.html', 'style.css', 'app.js', 'data.js', 'manifest.webmanifest']
for d in ['fonts', 'icons', 'audio']:
    for dp, _, fs in os.walk(os.path.join(ROOT, d)):
        for f in sorted(fs):
            if f.endswith(('.json',)) or f.startswith('.'): continue
            files.append(os.path.relpath(os.path.join(dp, f), ROOT))
h = hashlib.sha1()
for f in files:
    p = os.path.join(ROOT, f)
    if os.path.isfile(p): h.update(open(p, 'rb').read())
ver = h.hexdigest()[:10]
sw = f"""/* generated by tools/build_sw.py */
const VERSION = 'wes-reading-{ver}';
const FILES = {json.dumps(files)};
self.addEventListener('install', e => {{
  e.waitUntil((async () => {{
    const c = await caches.open(VERSION);
    // core first, then audio in batches; a single failed clip must not break install
    await c.addAll(FILES.slice(0, 6));
    const rest = FILES.slice(6);
    for (let i = 0; i < rest.length; i += 40) await Promise.all(rest.slice(i, i + 40).map(f => c.add(f).catch(() => {{}})));
    self.skipWaiting();
  }})());
}});
self.addEventListener('activate', e => {{
  e.waitUntil((async () => {{
    for (const k of await caches.keys()) if (k !== VERSION) await caches.delete(k);
    await self.clients.claim();
  }})());
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  e.respondWith((async () => {{
    const c = await caches.open(VERSION);
    const hit = await c.match(e.request, {{ ignoreSearch: true }});
    if (hit) return hit;
    try {{
      const r = await fetch(e.request);
      if (r.ok && r.status === 200) c.put(e.request, r.clone());
      return r;
    }} catch (err) {{
      if (e.request.mode === 'navigate') return (await c.match('index.html')) || Response.error();
      return Response.error();
    }}
  }})());
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
print('sw.js', ver, len(files), 'files')

#!/usr/bin/env python3
r"""Write sw.js with a precache list of every app file + audio clip and a content-hash version."""
import os, hashlib, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = ['./', 'index.html', 'style.css', 'app.js', 'data.js', 'manifest.webmanifest', 'version.js']
for d in ['fonts', 'icons', 'audio']:
    for dp, _, fs in os.walk(os.path.join(ROOT, d)):
        for f in sorted(fs):
            if f.endswith(('.json',)) or f.startswith('.'): continue
            files.append(os.path.relpath(os.path.join(dp, f), ROOT))
h = hashlib.sha1()
for f in files:
    p = os.path.join(ROOT, f)
    if os.path.isfile(p) and f != 'version.js': h.update(open(p, 'rb').read())
ver = h.hexdigest()[:10]
sw = f"""/* generated by tools/build_sw.py */
const VERSION = 'wes-reading-{ver}';
const FILES = {json.dumps(files)};
self.addEventListener('install', e => {{
  e.waitUntil((async () => {{
    const c = await caches.open(VERSION);
    // core first, then audio in batches; a single failed clip must not break install
    const get = (f) => fetch(new Request(f, {{ cache: 'reload' }})).then(r => {{ if (!r.ok) throw new Error(f); return c.put(f, r); }});
    await Promise.all(FILES.slice(0, 7).map(get));
    const rest = FILES.slice(7);
    for (let i = 0; i < rest.length; i += 40) await Promise.all(rest.slice(i, i + 40).map(f => get(f).catch(() => {{}})));
    self.skipWaiting();
  }})());
}});
self.addEventListener('activate', e => {{
  e.waitUntil((async () => {{
    for (const k of await caches.keys()) if (k !== VERSION) await caches.delete(k);
    await self.clients.claim();
  }})());
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  e.respondWith((async () => {{
    const c = await caches.open(VERSION);
    const range = e.request.headers.get('range');
    const hit = await c.match(range ? url.pathname : e.request, {{ ignoreSearch: true }}) || (range ? await c.match(e.request, {{ ignoreSearch: true, ignoreVary: true }}) : null);
    if (hit && range) {{
      // Safari's media player asks for byte ranges; answering with a full 200 makes playback fail/stall.
      const buf = await hit.arrayBuffer(), len = buf.byteLength;
      const m = /bytes=(\d*)-(\d*)/.exec(range) || [];
      let s = m[1] ? parseInt(m[1], 10) : 0, en = m[2] ? parseInt(m[2], 10) : len - 1;
      if (!m[1] && m[2]) {{ s = Math.max(0, len - parseInt(m[2], 10)); en = len - 1; }}
      en = Math.min(en, len - 1);
      if (s >= len || s > en) return new Response(null, {{ status: 416, headers: {{ 'Content-Range': 'bytes */' + len }} }});
      return new Response(buf.slice(s, en + 1), {{ status: 206, statusText: 'Partial Content', headers: {{
        'Content-Type': hit.headers.get('Content-Type') || 'audio/mpeg', 'Content-Range': 'bytes ' + s + '-' + en + '/' + len,
        'Content-Length': String(en - s + 1), 'Accept-Ranges': 'bytes' }} }});
    }}
    if (hit) return hit;
    try {{
      const r = await fetch(e.request);
      if (r.ok && r.status === 200) c.put(e.request, r.clone());
      return r;
    }} catch (err) {{
      if (e.request.mode === 'navigate') return (await c.match('index.html')) || Response.error();
      return Response.error();
    }}
  }})());
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
open(os.path.join(ROOT, 'version.js'), 'w').write("window.APP_BUILD='%s';\n" % ver)
print('sw.js', ver, len(files), 'files')
